-- 題庫資料夾分類
CREATE TABLE IF NOT EXISTS public.bank_folders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid text NOT NULL UNIQUE,
  name text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.problems
  ADD COLUMN IF NOT EXISTS bank_folder text REFERENCES public.bank_folders(uuid) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_problems_bank_folder ON public.problems(bank_folder);
