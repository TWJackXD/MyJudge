-- Materials table + problem visibility / PDF content support

CREATE TABLE IF NOT EXISTS public.materials (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid text NOT NULL UNIQUE,
  title text NOT NULL,
  file text NOT NULL,
  path text NOT NULL DEFAULT '',
  visibility text NOT NULL DEFAULT 'public',
  visibility_users jsonb NOT NULL DEFAULT '[]'::jsonb,
  uploaded_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
  uploaded_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_materials_uploaded_by ON public.materials(uploaded_by);

ALTER TABLE public.problems
  ADD COLUMN IF NOT EXISTS content_type text NOT NULL DEFAULT 'html',
  ADD COLUMN IF NOT EXISTS pdf_url text,
  ADD COLUMN IF NOT EXISTS visibility text NOT NULL DEFAULT 'public',
  ADD COLUMN IF NOT EXISTS visibility_users jsonb NOT NULL DEFAULT '[]'::jsonb;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'problems_content_type_check'
  ) THEN
    ALTER TABLE public.problems
      ADD CONSTRAINT problems_content_type_check
      CHECK (content_type = ANY (ARRAY['html'::text, 'pdf'::text]));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'problems_visibility_check'
  ) THEN
    ALTER TABLE public.problems
      ADD CONSTRAINT problems_visibility_check
      CHECK (visibility = ANY (ARRAY['public'::text, 'public_except'::text, 'private_except'::text, 'private'::text]));
  END IF;
END $$;

ALTER TABLE public.folders
  ADD COLUMN IF NOT EXISTS visibility text NOT NULL DEFAULT 'public',
  ADD COLUMN IF NOT EXISTS visibility_users jsonb NOT NULL DEFAULT '[]'::jsonb;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'folders_visibility_check'
  ) THEN
    ALTER TABLE public.folders
      ADD CONSTRAINT folders_visibility_check
      CHECK (visibility = ANY (ARRAY['public'::text, 'public_except'::text, 'private_except'::text, 'private'::text]));
  END IF;
END $$;

NOTIFY pgrst, 'reload schema';
